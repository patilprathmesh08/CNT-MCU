/**
  ******************************************************************************
  * @file    tls_credentials.h
  * @brief   Server TLS certificate/key material, embedded as DER byte arrays
  * @version 1.1 - 11-08-2026
  *
  * CHANGE IN 1.1: tls_server_cert_der[] re-issued (455 -> 535 bytes) to add a
  * subjectAltName, extendedKeyUsage=serverAuth and keyUsage=digitalSignature,
  * and to correct the Common Name to stm32h753-echo-server. The CA array and
  * the private-key array are BYTE-IDENTICAL to 1.0 - the same server keypair
  * was reused, so only the certificate changed. See the SUBJECT AND SAN block
  * below and docs/https_bringup_diagnosis_v1.4_cert_reissue_11082026.md.
  *
  * Generated from the Phase 1 PC-side PKI (certs/ca.crt, certs/server.crt,
  * certs/server.key) via: openssl x509/ec -outform DER, then converted to
  * C arrays. DER (not PEM) so mbedtls_x509_crt_parse()/mbedtls_pk_parse_key()
  * skip the PEM/Base64 unwrap step entirely (MBEDTLS_PEM_PARSE_C and
  * MBEDTLS_BASE64_C are deliberately not enabled in mbedtls_user_config.h).
  *
  * These arrays hold RAW DER bytes, NOT null-terminated C strings - always
  * pass the paired _len constant as the exact buffer length, never rely on
  * strlen() or a trailing 0x00.
  *
  * SUBJECT AND SAN - what clients actually check.
  *   Subject CN      : stm32h753-echo-server
  *   subjectAltName  : IP:192.168.1.10, DNS:stm32h753-echo-server
  *   extendedKeyUsage: serverAuth        keyUsage: critical, digitalSignature
  * The SAN is the part that matters. Modern clients - .NET, OpenSSL 4.x and
  * every browser - match the SAN and will NOT fall back to the CN, so a
  * certificate without one is rejected with a name mismatch no matter what its
  * CN says. Version 1.0 had no SAN, which is exactly the fault this fixes.
  *
  * THE SAN PINS 192.168.1.10. That is safe today because the address is static
  * (LWIP.LWIP_DHCP=0; LWIP/App/lwip.c sets it), but if the board is ever moved
  * to another address or to DHCP, THIS CERTIFICATE MUST BE RE-ISSUED or every
  * client will fail the name check. Nothing in the build will warn you.
  *
  * CORRECTION TO VERSION 1.0's COMMENT, which said re-issuing "requires the CA
  * private key, which is intentionally not available to this porting process".
  * That was wrong, and it is very likely why the missing SAN went unfixed from
  * 13-07-2026 to 11-08-2026. The CA private key IS available: six byte-identical
  * copies of ca.key live in the H573 projects' certs/ folders, e.g.
  * TCP_Server_H573_RTOS_V02/certs/ca.key, verified against ca.crt by matching
  * public-key SHA-256. server.key is in the same folders and matches too, which
  * is how the keypair could be reused here. Note ca.key being scattered across
  * project trees is itself contrary to TLS_Certificate_Guide_v1.md section 6.3.
  *
  * DIVERGED FROM THE OTHER H753 PROJECTS AS OF 11-08-2026. This file was
  * byte-identical across six projects (TCP_Server_H753_RTOS__ES_MBEDTLS_V00,
  * __MBEDTLS_V00, App1, App2, ETH_DualImage_Bootloader_H753_V01 and this one).
  * Only this one was re-issued, deliberately - the others are hardware-verified
  * and none of them serves HTTPS. The difference is intentional, not drift.
  *
  * DEVELOPMENT USE ONLY: server_key.der is a private key compiled directly
  * into flash in plaintext, extractable by anyone with SWD/JTAG access.
  * Fine for a lab bench; not appropriate for a production device - see the
  * production hardening discussion (TrustZone / secure key storage) from
  * the Phase 2 planning conversation. Note TrustZone is H5-specific
  * (STM32H753 has no TrustZone) - a production H753 design would need a
  * different secure-storage approach than that original discussion assumed.
  ******************************************************************************
  */

