/**
  * @brief  USART3 global interrupt - the ST-LINK Virtual COM Port.
  *
  * WRITTEN BY HAND BECAUSE NOTHING ELSE PROVIDES IT. USART3 belongs to the
  * NUCLEO BSP, not to CubeMX: it is not in the .ioc pinout at all, so no
  * handler is generated for it. The BSP does not supply one either, because its
  * own console is polled (blocking HAL_UART_Transmit in __io_putchar) and needs
  * no interrupt.
  *
  * vcom_tx.c uses HAL_UART_Transmit_IT to keep the console non-blocking, and
  * that requires this handler plus the NVIC enable in vcom_tx_init(). Without
  * both, the first transmit starts, the handle stays BUSY_TX for ever, and
  * every later printf is silently discarded by the HAL.
  *
  * Lives in USER CODE 1 so CubeMX regeneration cannot remove it. There is no
  * risk of a duplicate: CubeMX would only emit USART3_IRQHandler if USART3 were
  * added to the .ioc, which would also take the pins away from the BSP.
  */
void USART3_IRQHandler(void)
{
  HAL_UART_IRQHandler(&hcom_uart[COM1]);
}


