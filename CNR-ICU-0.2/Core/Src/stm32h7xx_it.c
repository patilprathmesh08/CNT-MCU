/**
  * @brief This function handles Ethernet global interrupt.
  */
void ETH_IRQHandler(void)
{
  /* USER CODE BEGIN ETH_IRQn 0 */

  /* ===== SCOPE TRIGGER: RISING EDGE - "an Ethernet frame arrived" =========
     THE EARLIEST POINT THIS CODE CAN REACH. Deliberately above
     HAL_ETH_IRQHandler(), so even the HAL's own descriptor walk and the
     semaphore release that wakes the lwIP input thread are inside the measured
     window. Anything below that call would already have missed them.

     FILTERED TO RECEIVE INTERRUPTS. ETH_IRQHandler is the ETH global vector: it
     also fires for transmit completion, and on the H7 for the error and
     early-receive conditions. Arming on a transmit interrupt would start pulses
     that have nothing to do with an inbound frame and inflate every reading, so
     the DMA channel status register is tested directly for RI (Receive
     Interrupt, bit 6) before doing anything.

     READ ONLY - the flag is NOT cleared here. Clearing it would swallow the
     interrupt that HAL_ETH_IRQHandler() is about to service and stall the
     receive path completely. The read is a single load from a peripheral
     register with no side effects. */
#if (SCOPE_TRIG_ENABLE && SCOPE_TRIG_FROM_ETH)
  if ((heth.Instance->DMACSR & ETH_DMACSR_RI) != 0U)
  {
    scope_trig_eth_rx();
  }
  else
  {
    /* Transmit-complete or an error interrupt - not an inbound frame. */
  }
#endif

  /* USER CODE END ETH_IRQn 0 */
  HAL_ETH_IRQHandler(&heth);
  /* USER CODE BEGIN ETH_IRQn 1 */

  /* USER CODE END ETH_IRQn 1 */
}

